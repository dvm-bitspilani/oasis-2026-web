// Navigation waits for artwork visible on entry, while the ordered background
// stage retains the complete manifests, including later form and modal assets.
export function criticalRouteResources(path: string): Resource[] {
  const route = path.split(/[?#]/)[0].replace(/\/$/, "").toLowerCase() || "/";
  switch (route) {
    case "/": return homeResources();
    case "/register": {
      const scroll = window.innerWidth <= 1075 ? "instructionsScrollLong.webp" : "instructionsScroll.webp";
      const google = window.innerWidth <= 577 ? "googleRegMob.svg" : "googleReg.svg";
      const initial = new Set([
        asset0, "/svgs/registration/birds.svg", "/game-icons_magic-lamp.svg",
        ...["closedBook.webp", "leftbottom.png", "rightbottom.png", "lefttop.png", "righttop.png", "rightmid.png", "regBackButton.webp", scroll, google]
          .map((file) => `https://res.cloudinary.com/bhfhuzru/image/upload/${file}`),
      ]);
      return registrationResources().filter((resource) => resource.type === "font" || initial.has(resource.url));
    }
    case "/events": return [
      ...[asset10, asset11, asset12, asset13, asset14, asset15, asset56, asset6, asset7, asset8]
        .map((url): Resource => ({ type: "image", url })),
      { type: "font", spec: "400 16px Syamsiah" },
      { type: "font", spec: "400 16px Ramadhan" },
    ];
    case "/aboutus": return aboutResources().filter((resource) => resource.type === "font" ||
      !/\/(?:bgCont\.png|bgVideo\.png|play\.webp|ffControl\.png|playBtn\.webp|scrollVid\.png)$/.test(resource.url));
    case "/contactus": {
      const parchment = window.innerWidth <= 729 ? asset55 : asset54;
      return contactResources().filter((resource) => resource.type === "font" ||
        (!resource.large && (resource.url !== asset54 && resource.url !== asset55 || resource.url === parchment)));
    }
    case "/comingsoon": return comingSoonResources();
    default: return [];
  }
}
